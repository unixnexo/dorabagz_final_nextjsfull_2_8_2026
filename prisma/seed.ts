function productCode(index: number) {
    return `PRD-TEST-${String(index + 1).padStart(3, "0")}`;
}

function slug(index: number) {
    return `product-test-${String(index + 1).padStart(3, "0")}`;
}

async function main() {
    // -------------------------------------------------------------------------
    // Admin
    // -------------------------------------------------------------------------

    const adminPhone = "09120000000";

    const admin = await prisma.user.upsert({
        where: { phoneNumber: adminPhone },
        update: { role: "ADMIN" },
        create: {
            phoneNumber: adminPhone,
            role: "ADMIN",
            fullName: "مدیر سیستم",
        },
    });

    console.log("✅ Admin user ready:", admin.phoneNumber);

    // -------------------------------------------------------------------------
    // Products
    // -------------------------------------------------------------------------

    console.log("🌱 Creating 50 test products...");

    // Persian year 1405 starts on 2026-03-21.
    // We store the actual Gregorian DateTime in PostgreSQL.
    // Your frontend can display it as Persian using fa-IR.
    const startDate = new Date("2026-03-21T10:00:00");

    for (let i = 0; i < products.length; i++) {
        const [title, description] = products[i];

        const createdAt = new Date(startDate);
        createdAt.setDate(createdAt.getDate() + i * 3);

        const product = await prisma.product.create({
            data: {
                title,
                description,

                slug: slug(i),
                productCode: productCode(i),

                isDeleted: false,
                createdAt,

                // Optional fields intentionally omitted:
                //
                // videoUrl
                // categoryId
                // images
                // specifications
                // options
            },
        });

        await prisma.productVariant.create({
            data: {
                productId: product.id,

                price: prices[i % prices.length],

                stock: 5 + (i % 20),
            },
        });

        console.log(
            `  ✓ ${i + 1}/50 - ${title}`
        );
    }

    console.log("✅ 50 test products created.");
}

main()
    .catch((e) => {
        console.error("❌ Seed failed:");
        console.error(e);
        process.exit(1);
    })
    .finally(async () => {
        await prisma.$disconnect();
    });


